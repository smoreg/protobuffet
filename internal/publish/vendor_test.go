const vendorToken = "vendor-token"

// registryWithSharedModule publishes a module whose protos another module
// wants to import.
func registryWithSharedModule(t *testing.T) *httptest.Server {
	t.Helper()
	store, err := registry.NewStore(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	catalog, err := registry.NewCatalog(store)
	if err != nil {
		t.Fatal(err)
	}
	cfg := config.DefaultServer()
	cfg.BaseURL = ""
	cfg.BreakingCheck = config.BreakingOff
	cfg.Tokens = []config.Token{{Subject: "t", SHA256: config.HashToken(vendorToken), Scopes: []string{"admin"}}}

	srv, err := api.New(cfg, catalog, slog.New(slog.NewTextHandler(io.Discard, nil)))
	if err != nil {
		t.Fatal(err)
	}
	ts := httptest.NewServer(srv.Handler())
	t.Cleanup(ts.Close)

	// The shared module, as `buffet publish` would store it: buf.yaml at the
	// root, protos under proto/.
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "buf.yaml"), "version: v2\nmodules:\n  - path: proto\n")
	writeFile(t, filepath.Join(dir, "proto/shared/v1/money.proto"),
		"syntax = \"proto3\";\npackage shared.v1;\nmessage Money { int64 minor = 1; }\n")
	archive, err := pack.Zip(dir, "", pack.SkipHidden)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := catalog.Publish(registry.PublishRequest{
		Module:    registry.Module{Owner: "acme", Name: "shared"},
		Version:   "v1.2.0",
		SchemaZip: archive,
		Artifacts: []registry.Artifact{{
			Target: registry.TargetGo, Name: "registry.test/gen/go/acme/shared",
			Version: "v1.2.0", File: "go.zip",
		}},
		Files:  map[string][]byte{"go.zip": []byte("zip")},
		Labels: []string{"stable"},
	}); err != nil {
		t.Fatal(err)
	}
	return ts
}

func writeFile(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func consumerModule(t *testing.T, deps string) *config.Module {
	t.Helper()
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "buf.yaml"), "version: v2\nmodules:\n  - path: proto\n")
	writeFile(t, filepath.Join(dir, "proto/catalog/v1/catalog.proto"),
		"syntax = \"proto3\";\npackage catalog.v1;\nimport \"shared/v1/money.proto\";\n")
	writeFile(t, filepath.Join(dir, "buffet.yaml"), `
version: v1
module: acme/catalog
proto: proto
`+deps+`
targets:
  go: {module: registry.test/gen/go/acme/catalog, template: buf.gen.go.yaml, out: gen/go}
`)
	m, err := config.LoadModule(dir)
	if err != nil {
		t.Fatal(err)
	}
	return m
}

func TestVendorFetchesDependencySchemas(t *testing.T) {
	ts := registryWithSharedModule(t)
	m := consumerModule(t, "deps:\n  - {module: acme/shared, version: v1.2.0}\n")

	vendored, err := publish.Vendor(context.Background(), client.New(ts.URL, vendorToken), m)
	if err != nil {
		t.Fatal(err)
	}
	if len(vendored) != 1 || vendored[0].Files == 0 {
		t.Fatalf("vendored = %+v", vendored)
	}

	// The dependency's protos land where its imports expect them.
	protoPath := filepath.Join(m.Dir, "third_party/acme/shared/proto/shared/v1/money.proto")
	if _, err := os.Stat(protoPath); err != nil {
		t.Fatalf("dependency proto not vendored: %v", err)
	}
	// Its buf.yaml must not survive, or buf sees a second module root.
	if _, err := os.Stat(filepath.Join(m.Dir, "third_party/acme/shared/buf.yaml")); !os.IsNotExist(err) {
		t.Error("the dependency's buf.yaml was kept")
	}

	// The generated workspace lists both roots and says it is generated.
	ws, err := os.ReadFile(filepath.Join(m.Dir, "buf.vendor.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"Generated by buffet vendor", "path: proto", "third_party/acme/shared/proto"} {
		if !strings.Contains(string(ws), want) {
			t.Errorf("buf.vendor.yaml missing %q:\n%s", want, ws)
		}
	}
}

func TestVendorResolvesALabel(t *testing.T) {
	ts := registryWithSharedModule(t)
	m := consumerModule(t, "deps:\n  - {module: acme/shared, version: stable}\n")

	vendored, err := publish.Vendor(context.Background(), client.New(ts.URL, vendorToken), m)
	if err != nil {
		t.Fatal(err)
	}
	if vendored[0].Version != "stable" {
		t.Errorf("version = %q", vendored[0].Version)
	}
	if _, err := os.Stat(filepath.Join(m.Dir, "third_party/acme/shared/proto/shared/v1/money.proto")); err != nil {
		t.Errorf("label did not resolve to an archive: %v", err)
	}
}

func TestVendorIsIdempotentAndDropsStaleCopies(t *testing.T) {
	ts := registryWithSharedModule(t)
	m := consumerModule(t, "deps:\n  - {module: acme/shared, version: v1.2.0}\n")
	c := client.New(ts.URL, vendorToken)

	if _, err := publish.Vendor(context.Background(), c, m); err != nil {
		t.Fatal(err)
	}
	// A file left from an earlier dependency compiles and hides the fact that
	// it is gone, so the directory is rebuilt rather than merged into.
	stale := filepath.Join(m.Dir, "third_party/removed/dep/proto/old.proto")
	writeFile(t, stale, "syntax = \"proto3\";\n")

	if _, err := publish.Vendor(context.Background(), c, m); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Error("a stale vendored file survived")
	}
}

func TestVendorWithoutDepsDoesNothing(t *testing.T) {
	ts := registryWithSharedModule(t)
	m := consumerModule(t, "")
	vendored, err := publish.Vendor(context.Background(), client.New(ts.URL, vendorToken), m)
	if err != nil || vendored != nil {
		t.Fatalf("vendored = %+v, err = %v", vendored, err)
	}
	if _, err := os.Stat(filepath.Join(m.Dir, "buf.vendor.yaml")); !os.IsNotExist(err) {
		t.Error("a workspace was written for a module with no deps")
	}
}

func TestVendorReportsAMissingDependency(t *testing.T) {
	ts := registryWithSharedModule(t)
	m := consumerModule(t, "deps:\n  - {module: acme/nope, version: v1.0.0}\n")
	_, err := publish.Vendor(context.Background(), client.New(ts.URL, vendorToken), m)
	if err == nil || !strings.Contains(err.Error(), "acme/nope") {
		t.Errorf("err = %v, want it to name the missing module", err)
	}
}
