package publish

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/smoreg/protobuffet/internal/client"
	"github.com/smoreg/protobuffet/internal/config"
	"github.com/smoreg/protobuffet/internal/pack"
)

// VendoredDep records what a vendor run fetched.
type VendoredDep struct {
	Module  string
	Version string
	Path    string
	Files   int
}

// Vendor downloads the schema archives of a module's dependencies into its
// vendor directory and writes a buf workspace that makes their imports
// resolve.
//
// This is the part of a registry buf assumes buf.build provides: `deps:` in
// buf.yaml resolves through the BSR and nowhere else. Vendoring from the
// registry you already run keeps a private schema graph working without it.
func Vendor(ctx context.Context, c *client.Client, m *config.Module) ([]VendoredDep, error) {
	if len(m.Deps) == 0 {
		return nil, nil
	}
	root := m.Path(m.Vendor)
	// The directory is derived state: stale copies of a dependency are worse
	// than no copies, because they compile.
	if err := os.RemoveAll(root); err != nil {
		return nil, fmt.Errorf("clean %s: %w", root, err)
	}

	var out []VendoredDep
	for _, dep := range m.Deps {
		archive, err := c.DownloadSchema(ctx, dep.Module, dep.Version)
		if err != nil {
			return nil, fmt.Errorf("fetch %s@%s: %w", dep.Module, dep.Version, err)
		}
		dir := filepath.Join(root, filepath.FromSlash(dep.Module))
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return nil, err
		}
		if err := pack.ExtractZip(archive, dir, false); err != nil {
			return nil, fmt.Errorf("unpack %s: %w", dep.Module, err)
		}
		// The archive carries the dependency's own buf.yaml; keeping it would
		// make buf treat the vendored copy as a second module root.
		if err := os.Remove(filepath.Join(dir, "buf.yaml")); err != nil && !os.IsNotExist(err) {
			return nil, err
		}
		_ = os.Remove(filepath.Join(dir, "buf.lock")) //nolint:errcheck // optional

		files, err := pack.Files(dir, pack.SkipHidden)
		if err != nil {
			return nil, err
		}
		out = append(out, VendoredDep{
			Module: dep.Module, Version: dep.Version, Path: dir, Files: len(files),
		})
	}
	if err := writeVendorWorkspace(m, out); err != nil {
		return nil, err
	}
	return out, nil
}

// vendorWorkspace is the buf v2 config listing the vendored proto roots
// alongside the module's own.
type vendorWorkspace struct {
	Version  string               `yaml:"version"`
	Modules  []vendorWorkspaceMod `yaml:"modules"`
	Lint     map[string]any       `yaml:"lint,omitempty"`
	Breaking map[string]any       `yaml:"breaking,omitempty"`
}

type vendorWorkspaceMod struct {
	Path    string   `yaml:"path"`
	Name    string   `yaml:"name,omitempty"`
	Exclude []string `yaml:"excludes,omitempty"`
}

// writeVendorWorkspace generates buf.vendor.yaml next to buf.yaml. It is
// generated rather than edited into buf.yaml so a vendor run never touches a
// file the developer maintains.
func writeVendorWorkspace(m *config.Module, deps []VendoredDep) error {
	ws := vendorWorkspace{
		Version: "v2",
		Modules: []vendorWorkspaceMod{{Path: cleanRel(m.Proto)}},
	}
	for _, d := range deps {
		rel, err := filepath.Rel(m.Dir, d.Path)
		if err != nil {
			return err
		}
		// A dependency archive holds its protos under its own proto
		// directory; point buf at that, not at the module folder.
		protoDir := filepath.Join(d.Path, "proto")
		if _, err := os.Stat(protoDir); err == nil {
			rel = filepath.Join(rel, "proto")
		}
		ws.Modules = append(ws.Modules, vendorWorkspaceMod{Path: filepath.ToSlash(rel)})
	}
	body, err := yaml.Marshal(ws)
	if err != nil {
		return err
	}
	header := "# Generated by buffet vendor. Do not edit; run `buffet vendor` again.\n" +
		"# Use it with: buf generate --config buf.vendor.yaml (or -c).\n"
	return os.WriteFile(filepath.Join(m.Dir, "buf.vendor.yaml"), append([]byte(header), body...), 0o644)
}

// VendorGitignore is the line a vendored directory wants in .gitignore.
func VendorGitignore(m *config.Module) string {
	return strings.TrimSuffix(m.Vendor, "/") + "/\n"
}
